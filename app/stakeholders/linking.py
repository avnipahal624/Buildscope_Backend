"""Link needs to existing solutions' features/limitations, and derive opportunity hypotheses."""
from sqlalchemy.orm import Session

from app.config import Settings
from app.models import NeedSolutionLink, Opportunity, SimilarProject, StakeholderNeed
from app.research.similarity import cosine
from app.stakeholders.strength import STRONGLY_SUPPORTED, SUPPORTED


def link_needs(db: Session, llm, run_id: str, project_id: str, needs: list[StakeholderNeed],
               research_run_id: str | None, settings: Settings) -> int:
    if not needs or not research_run_id:
        return 0
    projects = db.query(SimilarProject).filter_by(run_id=research_run_id).all()
    items: list[tuple[SimilarProject, str, str]] = []   # (project, relation, text)
    for sp in projects:
        items += [(sp, "related_feature", f) for f in (sp.features or [])]
        items += [(sp, "related_limitation", x) for x in (sp.limitations or [])]
    if not items:
        return 0
    vectors = llm.embed([n.need_text for n in needs] + [t for _, _, t in items])
    need_vecs, item_vecs = vectors[:len(needs)], vectors[len(needs):]

    created = 0
    for need, nv in zip(needs, need_vecs):
        scored = sorted(((cosine(nv, iv), it) for iv, it in zip(item_vecs, items)),
                        key=lambda t: t[0], reverse=True)
        for score, (sp, relation, text) in scored[:5]:
            if score < settings.link_threshold:
                break
            db.add(NeedSolutionLink(need_id=need.id, similar_project_id=sp.id,
                                    relation=relation, text=text, similarity=round(score, 4)))
            created += 1
    db.commit()
    return created


def derive_opportunities(db: Session, run_id: str, project_id: str, needs: list[StakeholderNeed]) -> int:
    """Rule-based hypotheses. Wording is generated by code so nothing is invented."""
    created = 0
    for need in needs:
        if need.evidence_status not in (SUPPORTED, STRONGLY_SUPPORTED):
            continue
        links = db.query(NeedSolutionLink).filter_by(need_id=need.id).all()
        limitation_links = [l for l in links if l.relation == "related_limitation"]
        feature_links = [l for l in links if l.relation == "related_feature"]
        if limitation_links:
            l = limitation_links[0]
            sp = db.get(SimilarProject, l.similar_project_id)
            desc = (f"Address: {need.need_text}. An existing solution ({sp.name}) documents a "
                    f"related limitation: \"{l.text}\".")
            ids = list({x.similar_project_id for x in limitation_links})
        elif not feature_links:
            desc = (f"Investigate: {need.need_text}. No related feature was found in the reviewed "
                    "projects' documentation (search coverage is incomplete).")
            ids = []
        else:
            continue          # already addressed by documented features
        db.add(Opportunity(
            project_id=project_id, run_id=run_id, origin="unmet_need", description=desc,
            rationale=f"Need status: {need.evidence_status} "
                      f"({need.independent_source_count} independent source(s)). Hypothesis only.",
            linked_need_ids=[need.id], linked_project_ids=ids, status="hypothesis"))
        created += 1
    db.commit()
    return created
